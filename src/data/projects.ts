import type { Project } from '@/types'
import { dayOffset, timestampOffset } from '@/lib/dates'

type Seed = Omit<Project, 'requirements' | 'customFields' | 'tags' | 'archived' | 'developerIds' | 'designerIds' | 'updatedAt' | 'pmStatus'> &
  Partial<Pick<Project, 'requirements' | 'customFields' | 'tags' | 'archived' | 'developerIds' | 'designerIds' | 'updatedAt' | 'pmStatus'>>

function project(p: Seed): Project {
  return {
    requirements: [],
    customFields: [],
    tags: [],
    archived: false,
    developerIds: [],
    designerIds: [],
    pmStatus: 'not_reviewed',
    updatedAt: p.createdAt,
    ...p,
  }
}

